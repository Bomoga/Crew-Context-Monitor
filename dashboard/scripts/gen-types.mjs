// Generate src/api/types.gen.ts from the JSON Schemas in ../contracts/api.
import { compile } from "json-schema-to-typescript";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const apiDir = join(here, "..", "..", "contracts", "api");
const out = join(here, "..", "src", "api", "types.gen.ts");

const pascal = (stem) =>
  stem
    .split("_")
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join("");

const banner = [
  "/* eslint-disable */",
  "// GENERATED by scripts/gen-types.mjs from contracts/api/*.schema.json. Do not edit.",
  "// Regenerate with `npm run gen:types` (or `make types`).",
  "",
].join("\n");

// json-schema-to-typescript cannot read the cards schema (prefixItems plus `items: false`), so
// for the TypeScript type only it becomes a fixed tuple of four Card. The JSON Schema itself,
// which also fixes the order of the domains, is unchanged and is what ajv validates against.
function tweak(stem, schema) {
  if (stem === "status") {
    const ref = { $ref: "#/$defs/card" };
    schema.properties.cards = {
      type: "array",
      description: schema.properties.cards.description,
      items: [ref, ref, ref, ref],
      minItems: 4,
      additionalItems: false,
    };
  }
  return schema;
}

let body = "";
const files = readdirSync(apiDir)
  .filter((f) => f.endsWith(".schema.json"))
  .sort();
for (const file of files) {
  const stem = file.replace(".schema.json", "");
  const schema = tweak(stem, JSON.parse(readFileSync(join(apiDir, file), "utf8")));
  schema.title = pascal(stem);
  body += await compile(schema, schema.title, {
    bannerComment: "",
    additionalProperties: false,
    format: true,
    style: { printWidth: 100 },
  });
  body += "\n";
}
writeFileSync(out, banner + "\n" + body.replace(/\n{3,}/g, "\n\n").trimEnd() + "\n");
console.log(`wrote ${out} from ${files.length} schemas`);
